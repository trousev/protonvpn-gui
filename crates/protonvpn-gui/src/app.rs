    /// The bug this pins: the account gate is a claim about what the CLI said, and when that
    /// claim is wrong or unknown the user must still be able to reach the sign-in form. Measured
    /// against the real CLI on 2026-10-01, `protonvpn info` logged out prints `Account: 'None'`,
    /// which used to read as a user called "None" — the login page never appeared and there was
    /// no way to sign in.
    #[test]
    fn the_sign_in_form_is_reachable_even_when_the_account_is_unknown() {
        let dir = std::env::temp_dir().join(format!("protonvpn-gui-app-{}", std::process::id()));
        let config = Config {
            // No `curl` and no real CLI: this test is about a window state, not about running
            // anything.
            probe_enabled: false,
            ..Default::default()
        };
        let mut options =
            EngineOptions::new(ConfigStore::at(dir.join("config.json")), config.clone());
        options.program = dir.join("no-such-cli").to_string_lossy().into_owned();
        let engine = protonvpn_core::engine::spawn(options);
        let (_tx, rx) = std::sync::mpsc::channel::<TrayCommand>();

        let mut app = App::new(
            engine,
            config,
            rx,
            None,
            window::Settings::default(),
            I18n::new(Locale::SOURCE),
        );

        // Nothing has been observed yet. Unknown is not "signed out", so the app shows the window
        // rather than inventing a verdict and the login page is not forced.
        assert!(!app.signed_out());
        assert!(!app.login_was_forced());

        let _ = app.update(Message::SignInRequested);
        assert!(app.login_was_forced(), "the user asked to sign in");

        let _ = app.update(Message::SignInCancelled);
        assert!(!app.login_was_forced());
    }

