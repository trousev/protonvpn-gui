/// The CLI's own three shortcuts. They are presets, not profiles: they carry no name, no country
/// and nothing editable, and they exist because `--p2p` and `--securecore` are real flags.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SystemPreset {
    Fastest,
    SecureCore,
    P2p,
}

impl SystemPreset {
    pub const ALL: [SystemPreset; 3] = [
        SystemPreset::Fastest,
        SystemPreset::SecureCore,
        SystemPreset::P2p,
    ];

    pub fn id(self) -> &'static str {
        match self {
            Self::Fastest => protonvpn_core::config::SYSTEM_FASTEST,
            Self::SecureCore => protonvpn_core::config::SYSTEM_SECURE_CORE,
            Self::P2p => protonvpn_core::config::SYSTEM_P2P,
        }
    }

    pub fn from_id(id: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|preset| preset.id() == id)
    }

    pub fn name(self) -> &'static str {
        match self {
            Self::Fastest => "Fastest",
            Self::SecureCore => "Secure Core",
            Self::P2p => "P2P",
        }
    }

    pub fn summary(self) -> &'static str {
        match self {
            Self::Fastest => "Быстрейший сервер",
            Self::SecureCore => "Двойной маршрут",
            Self::P2p => "Серверы для P2P",
        }
    }

    pub fn monogram(self) -> &'static str {
        match self {
            Self::Fastest => "F",
            Self::SecureCore => "SC",
            Self::P2p => "P2P",
        }
    }

    pub fn badges(self) -> &'static [&'static str] {
        match self {
            Self::Fastest => &[],
            Self::SecureCore => &["SECURE CORE"],
            Self::P2p => &["P2P", "ПОРТ"],
        }
    }

    pub fn target(self) -> ConnectTarget {
        match self {
            Self::Fastest => ConnectTarget::fastest(),
            Self::SecureCore => ConnectTarget {
                secure_core: true,
                ..Default::default()
            },
            Self::P2p => ConnectTarget {
                p2p: true,
                // A preset named after P2P is the one place a port mapping is meaningful: the CLI
                // only offers one on P2P-capable servers (`docs/cli-surface.md` §1).
                port_forwarding: true,
                ..Default::default()
            },
        }
    }
}

/// The target the selection stands for. An id that no longer resolves — a profile deleted in
/// another window, a hand-edited config — falls back to `connect`, and says so by being `Fastest`
/// rather than by pretending.
pub fn selected_target(config: &Config) -> ConnectTarget {
    match config.selected_connection.as_deref() {
        Some(id) => match SystemPreset::from_id(id) {
            Some(preset) => preset.target(),
            None => config
                .connection(id)
                .map(SavedConnection::target)
                .unwrap_or_else(ConnectTarget::fastest),
        },
        None => ConnectTarget::fastest(),
    }
}

