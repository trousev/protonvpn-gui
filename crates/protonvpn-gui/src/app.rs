//! The window — an elm-style update loop over the engine's snapshot.
//!
//! Views never call the runner (`docs/architecture.md` §1). Everything they do is a
//! [`Request`] sent to the engine, and everything they show comes from a snapshot plus the log
//! bus. That is what keeps the tray, the window and the interpreter from ever disagreeing about
//! what the CLI said.
//!
//! Three pieces of the contract are easy to lose in a UI and are therefore called out here:
//!
//! * **freshness is an age, never a verdict** (§7) — there is no "stale" badge anywhere below,
//! * **nothing is invented** (§5) — `Unknown` renders as its own words, not as "отключено",
//! * **the only program we run is `protonvpn`** (§0) — a connection profile is a way of spelling
//!   that program's argv, and the preview in the editor is generated by the launcher itself.
//!
//! The window has two shells. Signed out, it is the login page — a decision, not a tab, because
//! there is nothing else to do until `protonvpn info` names an account. Signed in, it is a
//! sidebar with two pages and the console pinned underneath both.

